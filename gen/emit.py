"""Render the op-list model as assembly, a C variant table, and prose.

Nothing here decides anything. If the rendered code is wrong, the model was
wrong, and validate.py simulates the model rather than the text.
"""

import isa


def _operands(op):
    return {"r%d" % i: isa.reg_name(op.instr, r) for i, r in enumerate(op.regs)}


def render_op(op, dev_reg, ram_reg):
    base = dev_reg if op.side == "dev" else ram_reg
    tmpl = op.instr.load if op.kind == "L" else op.instr.store
    text = tmpl.format(b=base, w=op.size, **_operands(op))
    return "    %-44s // %s %s +%-5d %2dB" % (
        text, op.side, "ld" if op.kind == "L" else "st", op.off, op.size)


def render_body(v):
    """One body. Every loop is `cmp / b.lo / ops / sub / b`, nothing else.

    The counter x2 is bytes remaining. Both pointers advance through
    post-index addressing on the accesses themselves, so there is no separate
    pointer arithmetic to get wrong, and the loop is a single comparison
    against a literal.
    """
    dev_reg = "x1" if v["dir"] == "rd" else "x0"   # rd: device is the source
    ram_reg = "x0" if v["dir"] == "rd" else "x1"
    name = "body_" + v["name"]
    L = []
    L.append("// %s" % ("-" * 68))
    L.append("// %s" % v["name"])
    L.append("//   %s   device %s (%dB)   RAM %s (%dB)"
             % ("device -> RAM" if v["dir"] == "rd" else "RAM -> device",
                v["dev"].id, v["dev"].width, v["ram"].id, v["ram"].width))
    L.append("//   block %d B   lookahead %d B   group %d B   %d %s registers (%s tier)"
             % (v["block"], v["la"], v["group"], v["need"],
                v["dev"].regclass.upper(), v["tier"]))
    for i in (v["dev"], v["ram"]):
        if i.note:
            L.append("//   %s: %s" % (i.id, i.note))
    L.append("//   x0 = dst, x1 = src, x2 = bytes (a multiple of %d)" % v["group"])
    L.append("    .global %s" % name)
    L.append("    .type   %s, %%function" % name)
    L.append("%s:" % name)
    lbl = 1
    for b in v["blocks"]:
        top, out = lbl, lbl + 1
        lbl += 2
        L.append("%d:  cmp  x2, #%d" % (top, b.nbytes))
        L.append("    b.lo %df" % out)
        for op in b.ops:
            L.append(render_op(op, dev_reg, ram_reg))
        L.append("    sub  x2, x2, #%d" % b.nbytes)
        L.append("    b    %db" % top)
        L.append("%d:" % out)
    L.append("    ret")
    L.append("    .size   %s, . - %s" % (name, name))
    return "\n".join(L)


def render_asm(vs):
    out = ["// Generated by gen/. Do not edit: edit the model and regenerate.",
           "// Every access uses post-index addressing; see gen/isa.py for why.",
           "    .text", ""]
    for v in vs:
        out.append(render_body(v))
        out.append("")
    return "\n".join(out)


def render_table(vs):
    out = ['/* Generated by gen/. Do not edit. */',
           '#include "variants.h"', '',
           "/* Each wrapper is head -> generated body -> tail; ht_copy holds the",
           "   head/tail logic so there is exactly one copy of it. */"]
    for v in vs:
        out.append("void body_%s(void *, const void *, unsigned long);" % v["name"])
    out.append("")
    for v in vs:
        out.append("static void fn_%s(void *d, const void *s, size_t n)\n"
                   "{ ht_copy(d, s, n, %s, %d, %d, body_%s); }"
                   % (v["name"], "DIR_RD" if v["dir"] == "rd" else "DIR_WR",
                      v["dev"].width, v["group"], v["name"]))
    out.append("")
    out.append("const struct variant variants[] = {")
    for v in vs:
        out.append('  { "%s", %s, "%s", %d, "%s", %d, %d, %d, %d, "%s", %d, fn_%s },'
                   % (v["name"], "DIR_RD" if v["dir"] == "rd" else "DIR_WR",
                      v["dev"].id, v["dev"].width, v["ram"].id, v["ram"].width,
                      v["block"], v["la"], v["group"], v["tier"], v["need"],
                      v["name"]))
    out.append("};")
    out.append("const size_t n_variants = sizeof variants / sizeof variants[0];")
    return "\n".join(out) + "\n"


def explain(v):
    """A human-readable trace of one variant, for reviewing by eye.

    Shows the block as a timeline of in-flight bytes, which is the quantity
    that both creates the overlap and consumes the registers.
    """
    out = ["%s" % v["name"],
           "  device %s %dB   RAM %s %dB   group %dB   block %dB   lookahead %dB"
           % (v["dev"].id, v["dev"].width, v["ram"].id, v["ram"].width,
              v["group"], v["block"], v["la"]),
           "  peak %d %s registers of %d available (%s tier)"
           % (v["need"], v["dev"].regclass.upper(),
              len(isa.TIERS[v["tier"]][v["dev"].regclass]), v["tier"])]
    for b in v["blocks"]:
        out.append("  block of %d bytes:" % b.nbytes)
        live = 0
        for op in b.ops:
            live += op.size if op.kind == "L" else -op.size
            out.append("    %-4s %-2s +%-5d %2dB  %-14s in flight %4d B"
                       % (op.side, "ld" if op.kind == "L" else "st", op.off,
                          op.size, ",".join(isa.reg_name(op.instr, r)
                                            for r in op.regs), live))
    return "\n".join(out)


def render_test_table(vs):
    """A table for the off-board body test. Deliberately independent of the
    harness: it exercises the generated bodies and nothing else."""
    out = ['/* Generated by gen/. Do not edit. */',
           '#include <stddef.h>',
           'typedef void (*body_fn)(void *, const void *, unsigned long);',
           'struct btest { const char *name; unsigned group; unsigned block;'
           ' int dir; body_fn fn; };', '']
    for v in vs:
        out.append("void body_%s(void *, const void *, unsigned long);" % v["name"])
    out.append("")
    out.append("const struct btest btests[] = {")
    for v in vs:
        out.append('  { "%s", %d, %d, %d, body_%s },'
                   % (v["name"], v["group"], v["block"],
                      0 if v["dir"] == "rd" else 1, v["name"]))
    out.append("};")
    out.append("const size_t n_btests = sizeof btests / sizeof btests[0];")
    return "\n".join(out) + "\n"

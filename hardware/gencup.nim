## Writes the stand, lid and board-outline SVGs to hardware/cup/ (`nim cup`).
import std/[os, strformat]
import receptacle, plates

const dir = "hardware/cup"
createDir dir
for f in walkFiles(dir / "*.svg"): removeFile f
var summary = "# Stand parts (generated by `nim cup`)\n\n| File | Part | Cut |\n|---|---|---|\n"
for part in PartKind:
  writeFile(dir / part.name & ".svg", part.partSvg)
  summary.add &"| [{part.name}.svg]({part.name}.svg) | {part.title} | ×{part.count} |\n"
summary.add &"""
All 3 mm plywood. Plates are {mm(2 * PlateApothem)} mm across flats. Height from
the base's top face to the lid: {mm(StripTop)} mm (sensor board gap {mm(BoardGap)},
floor {mm(Ply)}, pocket for {PocketTokens} tokens {mm(PocketHeight)}).
Slots are cut {mm(Fit)} mm oversize per side for the tabs; adjust `Fit` to your
plywood and laser kerf after a test cut.
"""
writeFile(dir / "top-view.svg", topViewSvg())
summary.add "\n[top-view.svg](top-view.svg) is a plan view for checking the fit, not a cut file.\n"
writeFile(dir / "README.md", summary)
echo "wrote ", dir

## Writes the cup, lid and board-outline SVGs to hardware/cup/ (`nim cup`).
import std/[os, strformat]
import receptacle, plates

const dir = "hardware/cup"
createDir dir
var summary = "# Cup parts (generated by `nim cup`)\n\n| File | Part | Cut |\n|---|---|---|\n"
for part in PartKind:
  writeFile(dir / part.name & ".svg", part.partSvg(SkirtOuterApothem))
  summary.add &"| [{part.name}.svg]({part.name}.svg) | {part.title} | ×{part.count} |\n"
let height = Ply * float(1 + BoardRings + 1 + PocketRings)
summary.add &"""
Cup: {mm(2 * OuterApothem)} mm across flats, {mm(height)} mm tall
(base, {BoardRings} board-zone rings, floor, {PocketRings} pocket rings), 3 mm plywood.
The pocket holds up to {PocketTokens} tokens; its floor is the baffle. The lid skirt is
{SkirtRings} rings deep, enough to cover the finger slots.
"""
writeFile(dir / "README.md", summary)
echo "wrote ", dir
